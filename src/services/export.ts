import { multiPolygonToPath } from '../geometry/polygon';
import type { MultiPolygon } from '../geometry/types';

export type ExportOptions = {
  region: MultiPolygon;
  paperColor: string;
  backgroundColor?: string | null;
  title: string;
  pixelSize?: number;
  padding?: number;
};

const PAD = 0.04;

function escapeXml(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export function slugify(title: string): string {
  const ascii = title
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\w\u4e00-\u9fa5-]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase();
  return ascii.length > 0 ? ascii.slice(0, 48) : 'papercut';
}

export function exportFileName(title: string, ext: 'svg' | 'png'): string {
  const d = new Date();
  const stamp = `${d.getFullYear()}${String(d.getMonth() + 1).padStart(2, '0')}${String(d.getDate()).padStart(2, '0')}`;
  return `foldyssey-${slugify(title)}-${stamp}.${ext}`;
}

/**
 * Build a standalone SVG document from the geometry engine output.
 *
 * The path comes straight from the computed MultiPolygon (with real inner rings
 * for holes) and uses `fill-rule="evenodd"`, so a hole stays a hole when the
 * file is opened offline. No bitmap is embedded.
 */
export function buildSvgDocument({
  region,
  paperColor,
  backgroundColor = null,
  title,
  pixelSize = 1200,
}: ExportOptions): string {
  const half = 1 + PAD;
  const d = multiPolygonToPath(region, 6);
  const bg = backgroundColor
    ? `<rect x="${-half}" y="${-half}" width="${half * 2}" height="${half * 2}" fill="${backgroundColor}"/>`
    : '';
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-half} ${-half} ${half * 2} ${half * 2}" width="${pixelSize}" height="${pixelSize}" role="img">
  <title>${escapeXml(title)}</title>
  <desc>Foldyssey · 一刀万象 — generated by a computational fold-and-cut engine.</desc>
  ${bg}
  <g transform="scale(1,-1)">
    <path d="${d}" fill="${paperColor}" fill-rule="evenodd"/>
  </g>
</svg>`;
}

function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

export function downloadSvg(options: ExportOptions): string {
  const svg = buildSvgDocument(options);
  const filename = exportFileName(options.title, 'svg');
  triggerDownload(new Blob([svg], { type: 'image/svg+xml;charset=utf-8' }), filename);
  return filename;
}

export async function downloadPng(options: ExportOptions & { pixelSize?: number }): Promise<string> {
  const size = options.pixelSize ?? 2048;
  const svg = buildSvgDocument({ ...options, pixelSize: size });
  const filename = exportFileName(options.title, 'png');
  const svgBlob = new Blob([svg], { type: 'image/svg+xml;charset=utf-8' });
  const url = URL.createObjectURL(svgBlob);
  try {
    const img = await loadImage(url);
    const canvas = document.createElement('canvas');
    canvas.width = size;
    canvas.height = size;
    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('Canvas 2D context unavailable');
    ctx.clearRect(0, 0, size, size);
    ctx.drawImage(img, 0, 0, size, size);
    const blob = await new Promise<Blob | null>((resolve) => canvas.toBlob(resolve, 'image/png'));
    if (!blob) throw new Error('PNG encoding failed');
    triggerDownload(blob, filename);
    return filename;
  } finally {
    URL.revokeObjectURL(url);
  }
}

function loadImage(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error('SVG rendering failed'));
    img.src = src;
  });
}

/** Copy helper used by the share card. */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    /* fall through */
  }
  try {
    const el = document.createElement('textarea');
    el.value = text;
    el.style.position = 'fixed';
    el.style.opacity = '0';
    document.body.appendChild(el);
    el.select();
    const ok = document.execCommand('copy');
    document.body.removeChild(el);
    return ok;
  } catch {
    return false;
  }
}
